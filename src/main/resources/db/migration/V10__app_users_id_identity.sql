-- V1 tạo id là BIGINT thường, nhưng entity User dùng GenerationType.IDENTITY.
-- Thêm identity để INSERT không truyền id (đăng ký user mới) hoạt động.
ALTER TABLE app_users
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Đẩy sequence qua id lớn nhất hiện có (ví dụ user seed id = 1) để không bị trùng khóa.
SELECT setval(
    pg_get_serial_sequence('app_users', 'id'),
    COALESCE((SELECT MAX(id) FROM app_users), 0) + 1,
    false
);
